import { dateISOManila, todayISO, vatBreakdown } from './format.js'

function formatPeso(val = 0) {
  return Number(val || 0).toLocaleString('en-PH', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })
}

function csvCell(val) {
  if (val == null) return '""'
  const str = String(val).replace(/"/g, '""')
  return `"${str}"`
}

function formatTime(isoDate) {
  if (!isoDate) return '—'
  try {
    return new Intl.DateTimeFormat('en-PH', {
      hour: 'numeric',
      minute: '2-digit',
      second: '2-digit',
      hour12: true,
      timeZone: 'Asia/Manila',
    }).format(new Date(isoDate))
  } catch {
    return '—'
  }
}

function formatDate(isoDate) {
  if (!isoDate) return '—'
  try {
    return new Intl.DateTimeFormat('en-PH', {
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      timeZone: 'Asia/Manila',
    }).format(new Date(isoDate))
  } catch {
    return isoDate
  }
}

/**
 * Exports today's collection data to a formatted, structured CSV template.
 */
export function exportDailyCollectionCsv(dailyRows = [], options = {}) {
  const today = options.today || todayISO()
  const staffName = options.profile?.full_name || options.profile?.email || 'Administrator'
  const generatedAt = new Intl.DateTimeFormat('en-PH', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
    timeZone: 'Asia/Manila',
  }).format(new Date())

  // Compute breakdown by payment method
  const methodMap = new Map()
  let totalGross = 0
  let totalVatable = 0
  let totalVat = 0

  dailyRows.forEach(({ payment }) => {
    const amt = Number(payment.amount || 0)
    totalGross += amt
    const vat = vatBreakdown(amt)
    totalVatable += vat.vatableSale
    totalVat += vat.vatAmount

    const method = String(payment.method || 'cash').toUpperCase()
    const cur = methodMap.get(method) || { count: 0, amount: 0 }
    methodMap.set(method, { count: cur.count + 1, amount: cur.amount + amt })
  })

  const lines = []

  // 1. Report Title & Header Block
  lines.push(['ISABEL WATERS UTILITY MANAGEMENT SYSTEM'].map(csvCell).join(','))
  lines.push(['OFFICIAL DAILY COLLECTION REPORT'].map(csvCell).join(','))
  lines.push('')
  lines.push(['REPORT METADATA'].map(csvCell).join(','))
  lines.push(['Report Date:', formatDate(today), '', 'Generated At:', `${generatedAt} PHT`].map(csvCell).join(','))
  lines.push(['Generated By:', staffName, '', 'Total Daily Transactions:', dailyRows.length].map(csvCell).join(','))
  lines.push(['Total Daily Collection:', `PHP ${formatPeso(totalGross)}`, '', 'Status:', 'Verified Active Payments'].map(csvCell).join(','))
  lines.push('')

  // 2. Payment Method Summary Table
  lines.push(['COLLECTION SUMMARY BY PAYMENT METHOD'].map(csvCell).join(','))
  lines.push(['Payment Method', 'Transactions', 'Total Amount (PHP)', 'Share of Collection'].map(csvCell).join(','))
  if (methodMap.size === 0) {
    lines.push(['No transactions recorded today', 0, '0.00', '0.0%'].map(csvCell).join(','))
  } else {
    methodMap.forEach((data, method) => {
      const share = totalGross > 0 ? ((data.amount / totalGross) * 100).toFixed(1) + '%' : '0.0%'
      lines.push([method, data.count, formatPeso(data.amount), share].map(csvCell).join(','))
    })
  }
  lines.push(['SUBTOTAL BY METHOD', dailyRows.length, formatPeso(totalGross), '100.0%'].map(csvCell).join(','))
  lines.push('')

  // 3. Detailed Transactions Table
  lines.push(['DAILY TRANSACTION AUDIT DETAILS'].map(csvCell).join(','))
  lines.push([
    'Time (PHT)',
    'Official Receipt / Ref No.',
    'Account No. (CAN)',
    'Customer Name',
    'Meter No.',
    'Bill No.',
    'Billing Month',
    'Payment Method',
    'Gross Amount (PHP)',
    'VATable Sale (PHP)',
    '12% VAT (PHP)',
    'Cashier / Staff',
  ].map(csvCell).join(','))

  if (dailyRows.length === 0) {
    lines.push(['—', '—', 'No transactions recorded for today', '—', '—', '—', '—', '—', '0.00', '0.00', '0.00', '—'].map(csvCell).join(','))
  } else {
    dailyRows.forEach(({ payment, bill, customer, cashier }) => {
      const amt = Number(payment.amount || 0)
      const vat = vatBreakdown(amt)
      lines.push([
        formatTime(payment.paid_at),
        payment.reference_no || `PAY-${payment.id?.slice(0, 8)}`,
        customer?.can || 'Pending',
        customer?.full_name || 'Walk-in Customer',
        customer?.meter_no || '—',
        bill?.bill_no || '—',
        bill?.billing_month ? String(bill.billing_month).slice(0, 7) : '—',
        String(payment.method || 'cash').toUpperCase(),
        formatPeso(amt),
        formatPeso(vat.vatableSale),
        formatPeso(vat.vatAmount),
        cashier?.full_name || cashier?.email || staffName,
      ].map(csvCell).join(','))
    })
  }

  // 4. Summary Totals & Sign-off Block
  lines.push('')
  lines.push(['FINANCIAL AUDIT TOTALS'].map(csvCell).join(','))
  lines.push(['Total Transactions Count:', dailyRows.length].map(csvCell).join(','))
  lines.push(['Total VATable Sales:', `PHP ${formatPeso(totalVatable)}`].map(csvCell).join(','))
  lines.push(['Total 12% VAT Amount:', `PHP ${formatPeso(totalVat)}`].map(csvCell).join(','))
  lines.push(['GRAND TOTAL COLLECTED TODAY:', `PHP ${formatPeso(totalGross)}`].map(csvCell).join(','))
  lines.push('')
  lines.push(['AUDIT CERTIFICATION'].map(csvCell).join(','))
  lines.push(['Certified Correct By:', '__________________________________________________'].map(csvCell).join(','))
  lines.push(['Designation:', 'Head Cashier / Collection Supervisor'].map(csvCell).join(','))
  lines.push(['Date Signed:', formatDate(today)].map(csvCell).join(','))

  const content = lines.join('\r\n')
  const blob = new Blob(['\uFEFF', content], { type: 'text/csv;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `isabel-waters-daily-collection-${today}.csv`
  link.click()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}

