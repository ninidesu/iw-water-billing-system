import assert from 'node:assert/strict'
import {billingDates,addDays,previousMonth,validateBillingDates} from '../src/lib/billingDates.js'
assert.deepEqual(billingDates('2026-11'),{period_start:'2026-11-01',period_end:'2026-11-30',due_date:'2026-12-10'})
assert.deepEqual(billingDates('2026-12'),{period_start:'2026-12-01',period_end:'2026-12-31',due_date:'2027-01-10'})
assert.equal(billingDates('2028-02').period_end,'2028-02-29')
assert.equal(billingDates('2027-02').due_date,'2027-03-10')
assert.equal(previousMonth('2026-01-15'),'2025-12')
assert.equal(addDays('2026-11-30',10),'2026-12-10')
const validate=(month,past,extra={})=>validateBillingDates({month,...billingDates(month),...extra},past,'2026-11-15')
assert.equal(validate('2026-11',false),'')
assert.equal(validate('2026-12',false),'')
assert.match(validate('2026-10',false),/past/)
assert.equal(validate('2026-10',true),'')
assert.match(validate('2026-11',true),/previous/)
assert.match(validate('2026-12',true),/previous/)
assert.match(validate('2026-11',false,{period_end:'2026-10-31'}),/Period end/)
assert.match(validate('2026-11',false,{due_date:'2026-11-29'}),/Due date/)
assert.equal(validate('2026-11',false,{period_start:'2026-11-02',period_end:'2026-11-28',due_date:'2026-12-05'}),'')
console.log('Billing-date checks passed: month restrictions, leap year, year rollover, custom periods, and due-date validation.')
